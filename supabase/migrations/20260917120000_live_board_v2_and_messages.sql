-- Reconcile the Live Board schema with the shipped client contract.
--
-- live-board.html loads live-board-messages-v2.js, which calls three RPCs that
-- were never committed to migrations (get_live_board_messages,
-- post_live_board_message, clear_live_board_messages). The short-access shim
-- (live-board-short-access.js) also redirects every room creation to an
-- untracked create_live_board_room_v2 that accepts p_student_short_token, and
-- 20260728124500_student_workspace_live_board_sessions.sql already inserts
-- into live_board_rooms.student_short_token_hash — a column no migration
-- created. Compact student links (#j=ROOM.<16-char token>) require the room
-- read/update RPCs to accept the short-token hash as well.
--
-- This migration is idempotent: it drops and recreates the seven affected
-- functions (any signature) so it is safe to apply whether or not hand-applied
-- versions exist in production, and it uses IF NOT EXISTS guards for the
-- column/table/FK.

begin;

-- Drop every existing overload of the affected functions. PostgREST resolves
-- RPCs by name and cannot pick between overloads; dropping first also lets us
-- change return types if production drifted.
do $$
declare
  fn record;
begin
  for fn in
    select p.oid::regprocedure::text as signature
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.proname in (
        'create_live_board_room',
        'create_live_board_room_v2',
        'get_live_board_room',
        'update_live_board_student',
        'get_live_board_messages',
        'post_live_board_message',
        'clear_live_board_messages'
      )
  loop
    execute format('drop function %s', fn.signature);
  end loop;
end;
$$;

-- Short student token column -------------------------------------------------

alter table public.live_board_rooms
  add column if not exists student_short_token_hash text;

-- Session messages table -----------------------------------------------------

create table if not exists public.live_board_messages (
  id bigint generated always as identity primary key,
  room_code text not null,
  sender_role text not null check (sender_role in ('teacher', 'student')),
  body text not null check (char_length(body) between 1 and 500),
  created_at timestamptz not null default now()
);

-- Defensive column adds in case a hand-applied table already exists.
alter table public.live_board_messages
  add column if not exists id bigint generated by default as identity;
alter table public.live_board_messages
  add column if not exists room_code text;
alter table public.live_board_messages
  add column if not exists sender_role text;
alter table public.live_board_messages
  add column if not exists body text;
alter table public.live_board_messages
  add column if not exists created_at timestamptz default now();

-- Messages die with their room: expiry sweeps and end_student_workspace_live_board
-- delete live_board_rooms rows, so the cascade removes their messages too.
do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'live_board_messages_room_code_fkey'
      and conrelid = 'public.live_board_messages'::regclass
  ) then
    alter table public.live_board_messages
      add constraint live_board_messages_room_code_fkey
      foreign key (room_code)
      references public.live_board_rooms(room_code)
      on delete cascade;
  end if;
end;
$$;

create index if not exists live_board_messages_room_idx
  on public.live_board_messages (room_code, created_at, id);

alter table public.live_board_messages enable row level security;
revoke all on table public.live_board_messages from anon, authenticated;

-- Room functions --------------------------------------------------------------

create function public.create_live_board_room(
  p_room_code text,
  p_teacher_token text,
  p_student_token text,
  p_fen text,
  p_pgn text default '',
  p_orientation text default 'white'
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_room public.live_board_rooms;
begin
  if p_room_code !~ '^[A-Z0-9]{6,12}$' then
    raise exception 'Invalid room code';
  end if;
  if length(p_teacher_token) < 32 or length(p_student_token) < 32 then
    raise exception 'Room tokens are too short';
  end if;
  if p_orientation not in ('white', 'black') then
    raise exception 'Invalid orientation';
  end if;

  delete from public.live_board_rooms where expires_at <= now();

  insert into public.live_board_rooms (
    room_code, teacher_token_hash, student_token_hash,
    student_short_token_hash, fen, pgn, orientation
  ) values (
    p_room_code,
    encode(extensions.digest(convert_to(p_teacher_token, 'UTF8'), 'sha256'), 'hex'),
    encode(extensions.digest(convert_to(p_student_token, 'UTF8'), 'sha256'), 'hex'),
    encode(extensions.digest(convert_to(left(p_student_token, 16), 'UTF8'), 'sha256'), 'hex'),
    p_fen,
    coalesce(p_pgn, ''),
    p_orientation
  )
  returning * into v_room;

  return jsonb_build_object(
    'room_code', v_room.room_code,
    'fen', v_room.fen,
    'pgn', v_room.pgn,
    'orientation', v_room.orientation,
    'last_move', v_room.last_move,
    'student_moves_allowed', v_room.student_moves_allowed,
    'revision', v_room.revision,
    'active_lesson_id', v_room.active_lesson_id,
    'expires_at', v_room.expires_at
  );
exception
  when unique_violation then
    raise exception 'Room code already exists';
end;
$$;

