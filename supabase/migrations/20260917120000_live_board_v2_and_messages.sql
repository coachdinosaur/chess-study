create function public.get_live_board_room(
  p_room_code text,
  p_access_token text
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
stable
as $$
declare
  v_room public.live_board_rooms;
  v_hash text;
begin
  v_hash := encode(extensions.digest(convert_to(coalesce(p_access_token, ''), 'UTF8'), 'sha256'), 'hex');

  select * into v_room
  from public.live_board_rooms
  where room_code = p_room_code
    and expires_at > now()
    and (teacher_token_hash = v_hash
         or student_token_hash = v_hash
         or student_short_token_hash = v_hash);

  if not found then
    raise exception 'Room not found or access token is invalid';
  end if;

  return jsonb_build_object(
    'room_code', v_room.room_code,
    'fen', v_room.fen,
    'pgn', v_room.pgn,
    'orientation', v_room.orientation,
    'last_move', v_room.last_move,
    'student_moves_allowed', v_room.student_moves_allowed,
    'revision', v_room.revision,
    'active_lesson_id', v_room.active_lesson_id,
    'expires_at', v_room.expires_at
  );
end;
$$;

create function public.update_live_board_student(
  p_room_code text,
  p_student_token text,
  p_expected_revision bigint,
  p_fen text,
  p_pgn text,
  p_last_move jsonb
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_room public.live_board_rooms;
  v_hash text;
begin
  v_hash := encode(extensions.digest(convert_to(coalesce(p_student_token, ''), 'UTF8'), 'sha256'), 'hex');

  update public.live_board_rooms
  set fen = p_fen,
      pgn = coalesce(p_pgn, ''),
      last_move = p_last_move,
      revision = revision + 1,
      updated_at = now(),
      expires_at = greatest(expires_at, now() + interval '12 hours')
  where room_code = p_room_code
    and (student_token_hash = v_hash or student_short_token_hash = v_hash)
    and expires_at > now()
    and student_moves_allowed
    and revision = p_expected_revision
  returning * into v_room;

  if not found then
    raise exception 'Student move rejected because the room is locked, stale, or access is invalid';
  end if;

  return jsonb_build_object(
    'room_code', v_room.room_code,
    'fen', v_room.fen,
    'pgn', v_room.pgn,
    'orientation', v_room.orientation,
    'last_move', v_room.last_move,
    'student_moves_allowed', v_room.student_moves_allowed,
    'revision', v_room.revision,
    'active_lesson_id', v_room.active_lesson_id,
    'expires_at', v_room.expires_at
  );
end;
$$;

-- Session message functions ---------------------------------------------------

create function public.get_live_board_messages(
  p_room_code text,
  p_access_token text
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
stable
as $$
declare
  v_hash text;
begin
  v_hash := encode(extensions.digest(convert_to(coalesce(p_access_token, ''), 'UTF8'), 'sha256'), 'hex');

  if not exists (
    select 1
    from public.live_board_rooms
    where room_code = p_room_code
      and expires_at > now()
      and (teacher_token_hash = v_hash
           or student_token_hash = v_hash
           or student_short_token_hash = v_hash)
  ) then
    raise exception 'Room not found or access token is invalid';
  end if;

  return (
    select coalesce(
      jsonb_agg(
        jsonb_build_object(
          'id', m.id,
          'sender_role', m.sender_role,
          'created_at', m.created_at,
          'body', m.body
        )
        order by m.created_at, m.id
      ),
      '[]'::jsonb
    )
    from (
      select id, sender_role, created_at, body
      from public.live_board_messages
      where room_code = p_room_code
      order by created_at desc, id desc
      limit 200
    ) m
  );
end;
$$;

create function public.post_live_board_message(
  p_room_code text,
  p_access_token text,
  p_body text
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_room public.live_board_rooms;
  v_message public.live_board_messages;
  v_hash text;
  v_role text;
  v_body text;
begin
  v_hash := encode(extensions.digest(convert_to(coalesce(p_access_token, ''), 'UTF8'), 'sha256'), 'hex');
  v_body := btrim(coalesce(p_body, ''));

  if char_length(v_body) not between 1 and 500 then
    raise exception 'Message body must be between 1 and 500 characters';
  end if;

  select * into v_room
  from public.live_board_rooms
  where room_code = p_room_code
    and expires_at > now();

  if not found then
    raise exception 'Room not found or access token is invalid';
  end if;

  -- Sender role is derived from the token, never supplied by the client, so
  -- a student token cannot post as the coach.
  if v_room.teacher_token_hash = v_hash then
    v_role := 'teacher';
  elsif v_room.student_token_hash = v_hash or v_room.student_short_token_hash = v_hash then
    v_role := 'student';
  else
    raise exception 'Room not found or access token is invalid';
  end if;

  insert into public.live_board_messages (room_code, sender_role, body)
  values (p_room_code, v_role, v_body)
  returning * into v_message;

  -- Chat counts as room activity, same as board updates.
  update public.live_board_rooms
  set expires_at = greatest(expires_at, now() + interval '12 hours')
  where room_code = p_room_code;

  -- Bound retained history per room.
  delete from public.live_board_messages
  where room_code = p_room_code
    and id not in (
      select id
      from public.live_board_messages
      where room_code = p_room_code
      order by created_at desc, id desc
      limit 500
    );

  return jsonb_build_object(
    'id', v_message.id,
    'room_code', v_message.room_code,
    'sender_role', v_message.sender_role,
    'created_at', v_message.created_at,
    'body', v_message.body
  );
end;
$$;

create function public.clear_live_board_messages(
  p_room_code text,
  p_teacher_token text
) returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, extensions
as $$
declare
  v_hash text;
begin
  v_hash := encode(extensions.digest(convert_to(coalesce(p_teacher_token, ''), 'UTF8'), 'sha256'), 'hex');

  if not exists (
    select 1
    from public.live_board_rooms
    where room_code = p_room_code
      and teacher_token_hash = v_hash
      and expires_at > now()
  ) then
    raise exception 'Room not found or access token is invalid';
  end if;

  delete from public.live_board_messages where room_code = p_room_code;

  return jsonb_build_object('cleared', true);
end;
$$;

